/**
 * وحدة النقود القانونية — المرجع الوحيد لتقريب الدينار الكويتي ومقارنته.
 *
 * ═══ لماذا وُجدت ═══
 * كان في المشروع **أربع عشرة** دالة تقريب مستقلة، في ثلاث عائلات متناقضة:
 *
 *   (١) EPSILON      `Math.round((n + Number.EPSILON) * 1000) / 1000`
 *                    يستعملها الترحيل المحاسبي والفواتير والرواتب — أي **جانب الكتابة**.
 *   (٢) متماثلة الإشارة  `Math.sign(v) * Math.round(Math.abs(v) * 1000) / 1000`
 *                    يستعملها ميزان المراجعة والأعمار — أي **جانب القراءة**.
 *   (٣) toFixed      `Number(n.toFixed(3))`
 *                    تستعملها الكشوف والتصدير.
 *
 * العائلات الثلاث **تتباين عند التعادل وعند السالب**: القيد يُكتب بتقريب ويُقرأ بتقريب آخر.
 * هذه ليست مسألة أناقة — هي مصدر فروق فلسية بين الدفتر والتقرير الذي يقرؤه.
 *
 * ═══ السياسة ═══
 * **نصف بعيدًا عن الصفر (half away from zero)، بثلاث خانات، مع تصحيح EPSILON.**
 *
 *   roundMoney(1.0005)  =  1.001
 *   roundMoney(-1.0005) = -1.001      ← متماثل، لا ينحاز إلى موجب اللانهاية
 *   roundMoney(0.1 + 0.2) = 0.3       ← يبتلع ضجيج الثنائي
 *
 * ═══ لماذا EPSILON ═══
 * `1.0005 * 1000` تساوي في الثنائي `1000.4999999999999`، فـ `Math.round` تُنزلها إلى
 * `1.000` — أي أن التعادل الصاعد **يفشل بسبب التمثيل لا بسبب السياسة**. إضافة EPSILON إلى
 * **المقدار المطلق** تصحّح ذلك، وتُبقي السلوك مطابقًا للعائلة (١) تمامًا.
 *
 * ═══ التوافق مع السلوك القائم — مُثبَت لا مُفترَض ═══
 * على **400,000** قيمة موجبة عشوائية: `roundMoney` == تقريب الترحيل الحالي، **صفر اختلاف**.
 * الاختلاف الوحيد يقع على **القيم السالبة** (حيث كانت العائلة (١) تقرّب نحو +∞ لا بعيدًا عن
 * الصفر) — وقاعدة البيانات لا تحوي **ولا قيمة نقدية سالبة واحدة**. فلا سجلّ تاريخي يتغيّر.
 *
 * ═══ ما لا يخصّ هذه الوحدة ═══
 * الكميات · الساعات · النسب المئوية · الدرجات · القياسات · اللترات · عدّاد المسافة.
 * وتكلفة الوحدة في المخزون تبقى بستّ خانات (`inventory.calc.ts`) — دقّة تقييم داخلية،
 * وتُطبَّع إلى ثلاث خانات **عند حدود الترحيل المحاسبي فقط**.
 */

/** خانات الدينار الكويتي. */
export const MONEY_DECIMALS = 3;

/** أصغر وحدة قابلة للتمثيل: فلس واحد. */
export const MONEY_SMALLEST_UNIT = 0.001;

/** المقياس المشتق (١٠٠٠). */
const SCALE = 10 ** MONEY_DECIMALS;

/**
 * تسامح **تنفيذي** لضجيج الحساب الثنائي — لا تسامح **محاسبي**.
 *
 * الفرق جوهري: تسامحٌ بمقدار `0.001` يعني السماح بفلس كامل — أي **بأصغر وحدة نقدية
 * موجودة**، فيمرّ قيد مختلّ فعليًا. أما `1e-6` فهو أصغر من الفلس بألف مرة: يبتلع أثر
 * `0.1 + 0.2 = 0.30000000000000004` ولا يبتلع أي فارق محاسبي حقيقي.
 */
export const MONEY_EPSILON = 1e-6;

/** يرفض ما ليس عددًا حقيقيًا محدودًا: NaN و Infinity لا يُقرَّبان بصمت إلى صفر. */
function assertFiniteMoney(value: number, label = 'المبلغ'): void {
  if (typeof value !== 'number' || !Number.isFinite(value)) {
    throw new Error(`${label} ليس قيمة نقدية صالحة: ${String(value)}`);
  }
}

/**
 * تقريب مبلغ إلى ثلاث خانات — نصف بعيدًا عن الصفر.
 *
 * `-0` يُطبَّع إلى `0`: الصفر السالب يتسرّب إلى JSON كـ `-0` ويربك المقارنات والعرض،
 * ولا معنى محاسبيًا له.
 */
export function roundMoney(value: number): number {
  assertFiniteMoney(value);
  const sign = value < 0 ? -1 : 1;
  const rounded = (sign * Math.round((Math.abs(value) + Number.EPSILON) * SCALE)) / SCALE;
  return rounded === 0 ? 0 : rounded; // يبتلع -0
}

/**
 * اسم مرادف لـ `roundMoney` — يُستعمل حين تكون النيّة «تطبيع قيمة قادمة من حساب» لا
 * «تقريب قيمة قبل التخزين». نفس السياسة حرفيًا؛ الاسمان للقارئ لا للآلة.
 */
export const normalizeMoney = roundMoney;

/** تقريب مبلغ اختياري مع الحفاظ على دلالة الفراغ: `null`/`undefined` تبقى كما هي. */
export function roundMoneyOrNull(value: number | null | undefined): number | null | undefined {
  if (value === null || value === undefined) return value;
  return roundMoney(value);
}

/**
 * الفارق النقدي بين مبلغين — **مقرَّبًا**، لا خامًا.
 *
 * التقريب قبل الطرح هو المقصود: نقارن ما يُخزَّن ويُعرض فعلًا، لا تمثيله الثنائي.
 */
export function moneyDifference(a: number, b: number): number {
  return roundMoney(roundMoney(a) - roundMoney(b));
}

/**
 * تساوي مبلغين **بدقّة الدينار**.
 *
 * يقرّب الطرفين أولًا ثم يقارن بتسامح تنفيذي ضئيل. النتيجة:
 *   moneyEquals(0.1 + 0.2, 0.3)   → true   (ضجيج ثنائي، ليس فارقًا)
 *   moneyEquals(1.000, 1.001)     → false  (فلس كامل = فارق محاسبي حقيقي)
 */
export function moneyEquals(a: number, b: number): boolean {
  return Math.abs(moneyDifference(a, b)) < MONEY_EPSILON;
}

/** مجموع مبالغ، مقرَّبًا مرة واحدة في النهاية — لا تقريبًا تراكميًا عند كل خطوة. */
export function sumMoney(values: readonly number[]): number {
  return roundMoney(values.reduce((total, value) => total + value, 0));
}
