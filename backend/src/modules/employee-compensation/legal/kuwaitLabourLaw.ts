/**
 * حدود العمل الإضافي المنصوص عليها في المادة ٦٦ — **كلها مذكورة، وليست كلها مفحوصة**.
 *
 * `verifiable` تقول الحقيقة عمّا يستطيع هذا النظام إثباته فعلًا: الوحدة تُدخَل
 * بإجماليات **شهرية** بلا سجل حضور يومي (Timesheet)، فلا سبيل إلى معرفة كيف توزّعت
 * الساعات على الأيام ولا كم يومًا شُغِّل فيها العامل إضافيًا.
 *
 * الحدّ الوحيد القابل للفحص فعليًا هو **١٨٠ ساعة سنويًا**، لأنه مجموع تراكمي لا يحتاج
 * تفصيلًا يوميًا — وتجمعه الخدمة من أشهر السنة المحفوظة. أما «ساعتان يوميًا» و«٣ أيام
 * أسبوعيًا» و«٩٠ يومًا سنويًا» فتُعرَض للعلم ولا يدّعي النظام التحقّق منها.
 */
export const OVERTIME_LIMITS = {
  /** ساعتان في اليوم الواحد — **غير قابل للفحص هنا** (لا سجل يومي). */
  maxHoursPerDay: { value: 2, verifiable: false as const },
  /** ١٨٠ ساعة في السنة — **مفحوص فعليًا** من مجموع أشهر السنة. */
  maxHoursPerYear: { value: 180, verifiable: true as const },
  /** ٣ أيام في الأسبوع — **غير قابل للفحص هنا** (لا سجل يومي). */
  maxDaysPerWeek: { value: 3, verifiable: false as const },
  /** ٩٠ يومًا في السنة — **غير قابل للفحص هنا** (لا سجل أيام تشغيل). */
  maxDaysPerYear: { value: 90, verifiable: false as const },
} as const;

/**
 * سقف شهري **مُشتَقّ حسابيًا لا منصوص عليه** — تنبيه إرشادي وحده، لا يمنع الحفظ.
 *
 * القانون يحدّ الساعات يوميًا (٢) والأيام أسبوعيًا (٣)، ولا يذكر سقفًا شهريًا إطلاقًا.
 * الرقم أدناه اشتقاق صريح: ٢ ساعة × ٣ أيام = ٦ ساعات أسبوعيًا × (٥٢ ÷ ١٢) أسبوعًا في
 * الشهر ≈ ٢٦ ساعة. يُقدَّم للمستخدم موسومًا `DERIVED` لا `STATUTORY`، ولا يُعرض بوصفه
 * نصًّا قانونيًا، ولا يُبنى عليه أي منع.
 */
export const DERIVED_MONTHLY_REGULAR_OVERTIME_CEILING =
  Math.round(OVERTIME_LIMITS.maxHoursPerDay.value * OVERTIME_LIMITS.maxDaysPerWeek.value * (52 / 12) * 100) / 100;

/** يتحقّق أن النص المدخل نوع عمل إضافي قانوني. */
export function isOvertimeType(value: unknown): value is OvertimeType {
  return typeof value === 'string' && (OVERTIME_TYPES as readonly string[]).includes(value);
}

/** قاعدة النوع — ترمي عند نوع غير قانوني بدل أن تعود بمعامل صامت. */
export function overtimeRule(type: OvertimeType): OvertimeRule {
  const rule = OVERTIME_RULES[type];
  if (!rule) throw new Error(`نوع عمل إضافي غير معروف: ${String(type)}`);
  return rule;
}
