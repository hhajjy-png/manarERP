/**
 * قواعد العمل الإضافي — قانون العمل في القطاع الأهلي الكويتي رقم ٦ لسنة ٢٠١٠.
 *
 * ═══ لماذا هنا وحدها ═══
 * هذا **المصدر الوحيد** لكل معامل قانوني وحدٍّ قانوني في وحدة مستحقات الموظف الشهرية.
 * لا نسخة ثانية في خدمة، ولا في مكوّن React، ولا في جدول إعدادات. القيم أدناه **غير
 * قابلة للتعديل من واجهة الإعدادات** عمدًا: هي نصّ قانون لا تفضيل مستخدم، وتعديلها من
 * شاشة إعدادات يعني السماح بصرف أقل من الحد القانوني بضغطة زر.
 *
 * تغييرُ أي قيمة هنا يستوجب **رفع `LEGAL_RULES_VERSION`**، لأن كل حسبة محفوظة تخزّن
 * إصدار القواعد الذي بُنيت عليه، فتبقى الكشوف التاريخية قابلة لإعادة الشرح بعد أي تعديل
 * قانوني لاحق.
 *
 * ═══ المواد المطبَّقة — كل نوع ومادّته ═══
 *
 *  • **المادة ٦٤** — ساعات العمل: لا يجوز تشغيل العامل أكثر من ٤٨ ساعة أسبوعيًا أو ٨
 *    ساعات يوميًا. (رمضان ٣٦ ساعة أسبوعيًا — مذكور للاكتمال، لا أثر له على أجر الساعة.)
 *
 *  • **المادة ٦٦** — **العمل الإضافي في يوم عمل عادي**: بأمر كتابي من صاحب العمل، وبما
 *    لا يجاوز ساعتين في اليوم، وأجر كل ساعة إضافية = **الأجر العادي للساعة + ٢٥٪ على
 *    الأقل**. وحدود التشغيل الإضافي: **ساعتان يوميًا · ١٨٠ ساعة سنويًا · ٣ أيام أسبوعيًا
 *    · ٩٠ يومًا سنويًا**.
 *
 *  • **المادة ٦٧** — **العمل في يوم الراحة الأسبوعية**: للعامل راحة أسبوعية بأجر مدتها
 *    ٢٤ ساعة متصلة بعد كل ستة أيام عمل. فإن اقتضت ظروف العمل تشغيله فيها، استحقّ
 *    **الأجر العادي + ٥٠٪ على الأقل**، **ويوم راحة بديلًا**.
 *
 *  • **المادة ٦٨** — **العمل في العطلات الرسمية**: إن اقتضت ظروف العمل تشغيل العامل في
 *    أحد أيام العطلات الرسمية، استحقّ **أجرًا مضاعفًا**، **ويوم راحة بديلًا**.
 *
 * تصحيح مقصود: كانت النسخة الأولى من هذا الملف تنسب الأنواع الثلاثة جميعًا إلى المادة
 * ٦٦. المادة ٦٦ تحكم **الإضافي في يوم العمل العادي وحده**؛ الراحة الأسبوعية مادتها ٦٧،
 * والعطلات الرسمية مادتها ٦٨. صُحّح المصدر المركزي هنا، ومنه تُشتقّ كل النصوص المعروضة
 * والمخزَّنة — لا نصّ مرجعٍ مكتوب يدويًا في أي طبقة أخرى.
 *
 * «على الأقل» في النصّ تعني أن النِّسَب أدناه **حدود دنيا**. المحرّك يطبّقها كما هي —
 * صرف أعلى منها قرار إداري يُدخَل كبند «استحقاق آخر»، لا كتلاعب في المعامل القانوني.
 */
