/**
 * حدود العمل الإضافي المنصوص عليها في المادة ٦٦ — **كلها مذكورة، وكلها صارت مفحوصة**.
 *
 * `verifiable` تقول الحقيقة عمّا يستطيع هذا النظام إثباته فعلًا. كانت ثلاثة من هذه
 * الحدود الأربعة `false` لسبب واحد لا غير: الوحدة كانت تُدخَل بإجماليات **شهرية** بلا
 * تواريخ، فلا سبيل إلى معرفة كيف توزّعت الساعات على الأيام ولا كم يومًا شُغِّل العامل.
 *
 * ═══ ما غيّرته حزمة السجل اليومي ═══
 * `OvertimeDayEntry` جعل لكل ساعة إضافية تاريخًا. الحدود الأربعة كلها صارت **مشتقّة من
 * بيانات موجودة فعلًا** لا مُفصحًا عنها:
 *   · ساعتان يوميًا  → `SUM(hours)` لكل تاريخ من نوع REGULAR.
 *   · ٣ أيام أسبوعيًا → عدد التواريخ الفريدة من نوع REGULAR داخل الأسبوع.
 *   · ٩٠ يومًا سنويًا → عدد التواريخ الفريدة من نوع REGULAR في السنة.
 *   · ١٨٠ ساعة سنويًا → كان مفحوصًا أصلًا، ويبقى.
 *
 * **`verifiable` هنا يعني «قابل للفحص متى توفّرت التفاصيل اليومية»، لا «مفحوص دائمًا».**
 * السجلّات الشهرية القديمة (بلا أي `OvertimeDayEntry`) تبقى بلا تواريخ إلى الأبد، ولا
 * يُدّعى فحص حدودها اليومية/الأسبوعية — يفرّق محرّك الالتزام بين الحالتين صراحةً بدل
 * أن يفترض أن غياب المخالفة يعني غياب التجاوز.
 */
