/**
 * قاسم الأجر اليومي — **مستورَد من خط الأساس القانوني الموثَّق للمشروع**، لا مُعاد
 * تعريفه هنا.
 *
 * ═══ لماذا استوردناه بدل كتابة رقم ═══
 * المستودع يحمل قرارًا قانونيًا **موثَّقًا ونهائيًا** في
 * `modules/employees/entitlements.calc.ts`:
 *
 *   «قاسم الأجر اليومي = ٢٦ — خط أساس قانوني معتمَد للمشروع (غير قابل لإعادة التقييم
 *    هنا)؛ ثابت واحد مركزي (DAILY_WAGE_DIVISOR) تشتق منه كل القيم اليومية دون تكرار.»
 *
 * ذلك القرار يحكم مكافأة نهاية الخدمة وبدل الإجازة في هذا النظام. اشتقاق أجر **الساعة**
 * من قاسم يومي مختلف كان سيجعل الشركة تحتسب «اليوم» بقيمتين متناقضتين في وحدتين من
 * النظام نفسه: ٤٨٠ ÷ ٢٦ = ١٨٫٤٦٢ د.ك لليوم عند التصفية، و٤٨٠ ÷ ٣٠ = ١٦٫٠٠٠ د.ك لليوم
 * ضمنيًا عند احتساب الإضافي. الاستيراد يجعل التناقض **مستحيلًا بنيويًا** لا مضبوطًا
 * بالانضباط: تغيير القاسم في مكانه الواحد يسري على الوحدتين معًا.
 *
 * ═══ ما تغيّر عن النسخة الأولى ═══
 * كانت v1 تستعمل ٣٠ يومًا (٢٤٠ ساعة شهريًا) استنادًا إلى «العرف السائد» — وهو ليس
 * مصدرًا داخل المستودع، بينما كان في المستودع قرار موثَّق يناقضه. اعتُمد القرار الموثَّق.
 * الأثر: أجر الساعة يرتفع بنسبة ٢٤٠ ÷ ٢٠٨ = **١٥٫٣٨٪**، وترتفع معه كل قيم الإضافي بنفس
 * النسبة — لصالح الموظف.
 *
 * ═══ الاستيراد ولا يخرق عزل الوحدة ═══
 * `modules/employees` مصدر قراءة مسموح صراحةً لهذه الوحدة، و`entitlements.calc.ts` وحدة
 * حسابية **نقيّة** بلا Prisma ولا أثر جانبي. المستورَد ثابت رقمي واحد لا خدمة ولا كتابة.
 */
export const MONTHLY_WAGE_DAYS_DIVISOR = DAILY_WAGE_DIVISOR;

/** ساعات العمل الشهرية المعتمدة لاشتقاق أجر الساعة (٢٦ × ٨ = ٢٠٨). */
export const MONTHLY_WORK_HOURS = MONTHLY_WAGE_DAYS_DIVISOR * STANDARD_HOURS_PER_DAY;

/** أنواع العمل الإضافي القانونية. القائمة مغلقة — لا نوع خارج نصّ القانون. */
export const OVERTIME_TYPES = ['REGULAR', 'WEEKLY_REST', 'OFFICIAL_HOLIDAY'] as const;
export type OvertimeType = (typeof OVERTIME_TYPES)[number];

export interface OvertimeRule {
  readonly type: OvertimeType;
  /** الاسم العربي المعروض. */
  readonly labelAr: string;
  /**
   * معامل احتساب الساعة الإضافية — يُضرب في **أجر الساعة العادي**.
   * ١٫٢٥ = «الأجر العادي + ٢٥٪»، ١٫٥٠ = «+ ٥٠٪»، ٢٫٠٠ = «أجر مضاعف».
   */
  readonly multiplier: number;
  /** رقم المادة الحاكمة لهذا النوع وحده. */
  readonly article: 66 | 67 | 68;
  /** المرجع القانوني الحرفي — يُخزَّن مع كل سطر ويظهر في التقرير التفصيلي وحده. */
  readonly legalReference: string;
  /** هل يستحق العامل **يوم راحة بديلًا** إضافةً إلى الأجر؟ (المادتان ٦٧ و٦٨) */
  readonly compensatoryRestDay: boolean;
}

