  Math.round(OVERTIME_LIMITS.maxHoursPerDay.value * OVERTIME_LIMITS.maxDaysPerWeek.value * (52 / 12) * 100) / 100;

/**
 * ═══ متطلبات قانونية قائمة **لا يطبّقها هذا النظام** — مراجعة القرار ١٨٨/ع لسنة ٢٠١٠ ═══
 *
 * راجعنا القرار الوزاري ١٨٨/ع لسنة ٢٠١٠ (ساعات العمل الإضافي في القطاع الخاص) مقابل
 * المطبَّق هنا. **لم يُغيَّر أي حدٍّ أو معامل**: حدود المادة ٦٦ الأربعة المطبَّقة أعلاه
 * (ساعتان يوميًا · ٣ أيام أسبوعيًا · ١٨٠ ساعة سنويًا · ٩٠ يومًا سنويًا) والمعاملات
 * (٢٥٪ · ٥٠٪ · مضاعف) مطابقة لما تنصّ عليه المصادر.
 *
 * لكن ثلاثة متطلبات قائمة **خارج قدرة هذه الوحدة**، وتُذكر هنا كي لا يُفهم صمتُ النظام
 * عنها على أنها مستوفاة:
 *
 *  ١) **الأمر الكتابي** — المادة ٦٦ والقرار ١٨٨ يشترطان أن يكون التشغيل الإضافي بأمر
 *     كتابي من صاحب العمل، وأن تقتضيه ضرورة (كمنع وقوع خسارة). هذه الوحدة تسجّل
 *     **ساعات وأجرًا**، ولا تسجّل وجود ذلك الأمر ولا سببه. فوجودُ سطر إضافي هنا ليس
 *     دليلًا على استيفاء الشرط الشكلي.
 *
 *  ٢) **المادة ٦٥** — لا يُشغَّل العامل أكثر من خمس ساعات متصلة دون راحة لا تقلّ عن
 *     ساعة. الوحدة تسجّل **مجموع ساعات اليوم** بلا أوقات بداية ونهاية، فلا تستطيع
 *     معرفة الاتصال ولا فترات الراحة — غير قابل للفحص هنا بنيويًا.
 *
 *  ٣) **المادة ٦٤ — مجموع ساعات الأسبوع (٤٨)** — تُسجَّل هنا ساعات الإضافي وحدها دون
 *     ساعات العمل العادية، فمجموع الأسبوع غير محسوب. (يُفصح عنه محرّك الالتزام صراحةً.)
 *
 * ═══ غموض قانوني غير محسوم ═══
 * وقوعُ **العطلة الرسمية في يوم الراحة الأسبوعية** لا تعالجه المادتان ٦٧ و٦٨ ولا القرار
 * ١٨٨: لا نصّ على جمع المعاملين، ولا على ترجيح أحدهما، ولا على عدد أيام الراحة البديلة
 * المستحقّة حينئذ. النظام **لا يفترض قاعدة**: يرفض تصنيف اليوم بنوعين ويعرض المسألة
 * بوصفها قرارًا يحتاج إدارة الشركة (انظر `overtimeDayLedger.ts`).
 *
 * تحفّظ على المصدر: تعذّر تنزيل نصّ القرار ١٨٨ من موقع الهيئة العامة للقوى العاملة وقت
 * المراجعة (خطأ خادم)، والتأكيد أعلاه مستند إلى مصادر ثانوية متطابقة. أي تعديل قانوني
 * لاحق يجب أن يُبنى على النصّ الرسمي مباشرةً، ويستوجب رفع `LEGAL_RULES_VERSION`.
 */

/** يتحقّق أن النص المدخل نوع عمل إضافي قانوني. */
export function isOvertimeType(value: unknown): value is OvertimeType {
  return typeof value === 'string' && (OVERTIME_TYPES as readonly string[]).includes(value);
}

/** قاعدة النوع — ترمي عند نوع غير قانوني بدل أن تعود بمعامل صامت. */
export function overtimeRule(type: OvertimeType): OvertimeRule {
  const rule = OVERTIME_RULES[type];
  if (!rule) throw new Error(`نوع عمل إضافي غير معروف: ${String(type)}`);
  return rule;
}
