/**
 * التقريب داخل محرّك مستحقات الموظف.
 *
 * **النقود** ليست من شأن هذا الملف: سياسة الدينار الكويتي (ثلاث خانات، نصف بعيدًا عن
 * الصفر) تملكها `shared/utils/money` وحدها، ونُعيد تصديرها هنا حتى لا يُغرى مستدعٍ
 * بكتابة تقريب ثانٍ. ما يخصّ هذا الملف هو تقريب **الساعات** — وهي ليست نقودًا وقاعدتها
 * مختلفة تمامًا.
 */
import { roundMoney, sumMoney } from '../../../shared/utils/money';

export { roundMoney, sumMoney };

/**
 * تسامح الضجيج الثنائي عند تقريب الساعات لأعلى.
 *
 * `840 ÷ (2.8 × 1.25)` تساوي رياضيًا `240`، وتساوي في الثنائي أحيانًا
 * `239.99999999999997`. `Math.ceil` وحدها كانت سترفعها إلى **٢٤١** — أي ساعة كاملة
 * وهمية سببها التمثيل لا الحساب. العتبة أصغر من أي جزء ساعة ذي معنى (١e-٩ ساعة ≈ ٣٫٦
 * ميكروثانية)، فلا تبتلع أي كسر حقيقي: `10.000000001` تبقى ١١، و`10.0` تبقى ١٠.
 */
export const HOURS_EPSILON = 1e-9;

/**
 * تقريب الساعات **لأعلى إلى ساعة كاملة — لصالح الموظف** (المتطلب ١٢).
 *
 *   10.0  → 10      (ساعة كاملة بالضبط: لا رفع)
 *   10.01 → 11
 *   10.1  → 11
 *   10.9  → 11
 *   0.01  → 1
 *   0     → 0
 *
 * أي جزء من ساعة — مهما صغر — يصير ساعة كاملة. القاعدة **في مصلحة الموظف دائمًا**،
 * فالمبلغ الناتج قد يعلو قليلًا عن المبلغ المستهدف، وذلك مقصود لا انحراف.
 */
export function ceilHoursInFavourOfEmployee(hours: number): number {
  if (!Number.isFinite(hours)) throw new Error(`عدد الساعات ليس قيمة صالحة: ${String(hours)}`);
  if (hours <= 0) return 0;
  const ceiled = Math.ceil(hours - HOURS_EPSILON);
  // `Math.ceil(0.0000000005 - 1e-9)` تعطي `-0`؛ الصفر السالب يتسرّب إلى JSON ويربك العرض.
  return ceiled === 0 ? 0 : ceiled;
}

/**
 * تطبيع عدد ساعات مُدخَل يدويًا — ثلاث خانات عشرية.
 *
 * الساعات ليست نقودًا، لكنها تُدخَل كسورًا (٧٫٥ ساعة) وتحتاج حدًّا للدقة كي لا يتسرّب
 * `7.500000000000001` إلى قاعدة البيانات ومنها إلى الكشف.
 */
export function normalizeHours(hours: number): number {
  if (!Number.isFinite(hours)) throw new Error(`عدد الساعات ليس قيمة صالحة: ${String(hours)}`);
  const rounded = Math.round(hours * 1000) / 1000;
  return rounded === 0 ? 0 : rounded;
}
