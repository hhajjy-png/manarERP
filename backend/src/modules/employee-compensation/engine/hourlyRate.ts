/**
 * اشتقاق أجر الساعة العادي من الراتب الأساسي الشهري.
 *
 * الأساس القانوني وقاسم الأيام (والنقطة غير المحسومة فيه) موثّقان بالكامل في
 * `legal/kuwaitLabourLaw.ts`. هذا الملف حساب بحت لا رأي قانونيًا فيه.
 *
 * ═══ لماذا يُقرَّب أجر الساعة إلى ثلاث خانات ═══
 * أجر الساعة **مبلغ بالدينار**، ويُطبع في التقرير التفصيلي بوصفه الرقم الذي يستطيع
 * قارئ الكشف أن يعيد منه الحساب بنفسه. لو احتُفظ به خامًا (`2.1666666…`) لظهر مقرَّبًا
 * في الورقة بينما الاحتساب جرى على قيمة أخرى، فلا يُعاد اشتقاق أي سطر من الأرقام
 * المطبوعة. التقريب هنا يجعل المستند **قابلًا لإعادة الحساب حرفيًا**، وأثره أصغر من
 * نصف فلس في الساعة.
 */
import { MONTHLY_WORK_HOURS } from '../legal/kuwaitLabourLaw';
import { roundMoney } from './rounding';

/**
 * أجر الساعة العادي = الراتب الأساسي الشهري ÷ ساعات العمل الشهرية المعتمدة.
 *
 * يرمي عند راتب غير موجب: كشفٌ بأجر ساعة صفر يُنتج «صفر دينار عن ١١ ساعة» بصمت،
 * وهو خطأ صرفٍ لا نتيجةَ حساب.
 */
export function computeHourlyRate(basicMonthlySalary: number): number {
  if (!Number.isFinite(basicMonthlySalary)) {
    throw new Error(`الراتب الأساسي ليس قيمة صالحة: ${String(basicMonthlySalary)}`);
  }
  if (basicMonthlySalary <= 0) {
    throw new Error('الراتب الأساسي يجب أن يكون أكبر من صفر لاحتساب أجر الساعة');
  }
  return roundMoney(basicMonthlySalary / MONTHLY_WORK_HOURS);
}
