/* ════════════════════════════════════════════════════════════════════════════
   Timeline Search — بناء نمط بحث محايد لرسم الحروف العربية
   --------------------------------------------------------------------------
   المشكلة المُثبتة في التدقيق: `contains` الخام يفشل حين يختلف رسم الحرف —
   «إحالة» لا تطابق «احالة»، و«شركه» لا تطابق «شركة». تطبيع نص البحث وحده لا
   يكفي لأن النص المخزَّن غير مُطبَّع، وتطبيع المخزَّن يتطلب تعديل قاعدة
   البيانات (ممنوع).

   الحل: استغلال محرف البدل `_` في LIKE — وهو يطابق **محرفًا واحدًا** تمامًا،
   وكل حروف العائلة العربية المتغيّرة (أ إ آ ا / ة ه / ى ي) محرف واحد. فيصبح
   «إحالة» → «_ح_ل_» فيطابق كل الرسمات دون لمس التخزين ولا الفهارس.

   وأيضًا: تُزال `%` و`_` التي يكتبها المستخدم قبل البناء، لأن Prisma لا يوفّر
   `ESCAPE` فتتحوّل إلى محارف بدل غير مقصودة (إيجابيات كاذبة).

   PURE. لا Prisma، لا I/O.
   ════════════════════════════════════════════════════════════════════════════ */

/** عائلات الحروف التي يختلف رسمها ويجب ألا تُفشل البحث. */
const ORTHOGRAPHIC_FAMILIES = /[أإآاٱ]|[ةه]|[ىي]/g;

/** التشكيل والتطويل — يُحذف من النمط لأنه نادرًا ما يُكتب في البحث. */
const DIACRITICS = /[ً-ْـ]/g;

/** محارف بدل LIKE التي يكتبها المستخدم — تُزال لأنها لا تُهرَّب عبر Prisma. */
const LIKE_WILDCARDS = /[%_]/g;

/**
 * يحوّل نص بحث المستخدم إلى نمط `contains` محايد لرسم الحروف.
 * يُعيد `undefined` لأي نص فارغ بعد التنظيف — فيُسقَط الفلتر بدل بناء نمط فارغ
 * يطابق كل شيء.
 */
export function buildSearchPattern(raw?: string | null): string | undefined {
  if (!raw) return undefined;
  const cleaned = String(raw)
    .replace(DIACRITICS, '')
    .replace(LIKE_WILDCARDS, '')
    .replace(/\s+/g, ' ')
    .trim();
  if (!cleaned) return undefined;
  return cleaned.replace(ORTHOGRAPHIC_FAMILIES, '_');
}

/**
 * الحقول المعروضة للمستخدم والقابلة للبحث. أي معرّف يراه المستخدم في الجدول أو
 * الدرج يجب أن يكون قابلًا للبحث — وإلا كان الفلتر يُخفي حركة موجودة.
 */
export const SEARCHABLE_FIELDS = [
  'description',
  'reference',
  'chequeNumber',
  'matchedRef',
  'transactionId',
] as const;

export type SearchableField = (typeof SEARCHABLE_FIELDS)[number];
