import fs from 'fs';
import net from 'net';
import { REAL_DEV_DB, SANDBOX_ROOT, TestIsolationError, sha256OfFile } from './vitest.sandbox';

/**
 * Test Isolation Pack v1 — حارس التشغيل الكامل.
 *
 * يعمل **مرّة واحدة** في العملية الرئيسية: قبل أي عامل، وبعد آخر عامل.
 *
 * ── لماذا حارس بصمة وليس ثقة بالإعداد ─────────────────────────────────────────
 *
 * `vitest.setup.ts` يمنع الوصول عبر إعادة توجيه البيئة، وهو المنع الفعلي. لكن
 * «منعتُ الوصول» ادّعاء، و«الملف لم يتغيّر» إثبات. هذا الحارس يحوّل الضمانة من
 * تصميم يُصدَّق إلى **حقيقة تُقاس**: بصمة SHA-256 لقاعدة التطوير تُلتقط قبل أول
 * اختبار وتُقارَن بعد آخر واحد، وأي فارق يُفشل التشغيل كله برسالة صريحة.
 *
 * يغطّي هذا ما لا تغطّيه إعادة التوجيه وحدها: اختبار يكتب بمسار مطلق مباشر عبر
 * `fs`، أو عملية فرعية يُطلقها اختبار، أو أي طريق لم يخطر ببال أحد. لا يعرف
 * الحارس **كيف** وقعت الكتابة — يعرف فقط أنها وقعت، وهذا يكفي لإيقاف التشغيل.
 *
 * ── لماذا لا يفشل عند غياب القاعدة ────────────────────────────────────────────
 *
 * جهاز CI نظيف لا يملك `backend/data/manar.db`. الغياب حالة مشروعة تمامًا: لا ملف
 * محمي ⇒ لا شيء يُنتهَك. الحارس يتخطّى بصمت بدل أن يُفشل تشغيلًا سليمًا.
 */

/** منفذ الخدمة الخلفية — ثابت في هذا المشروع (`env.PORT` الافتراضي). */
const BACKEND_PORT = 48211;

/**
 * هل يوجد خادم خلفي حيّ يمسك قاعدة التطوير الآن؟
 *
 * ── لماذا يلزم هذا التمييز ─────────────────────────────────────────────────────
 *
 * الحارس يسأل «هل تغيّر الملف؟»، وهو سؤال صحيح ما دام **لا كاتب غيرنا**. لكن
 * المطوّر قد يُشغّل `npm test` والتطبيق مفتوح أمامه: عندها يكتب الخادمُ الحيّ سجلَّ
 * تدقيق أو نسخة مجدولة أثناء التشغيل، فتتغيّر البصمة لسبب **لا علاقة له
 * بالاختبارات إطلاقًا**.
 *
 * إفشال التشغيل حينها ليس صرامة بل ضوضاء: إنذار كاذب متكرر يُدرِّب الناس على
 * تجاهل الحارس، فيموت وهو أخضر. لذلك تُميَّز الحالتان صراحةً: انتهاك مُثبَت يُفشل،
 * ونتيجة غير حاسمة تُبلَّغ بوضوح.
 *
 * الفحص بمحاولة الاستماع لا بالاتصال: `EADDRINUSE` دليل قاطع على وجود مالك للمنفذ،
 * ولا يفتح أي اتصال بالخدمة ولا يُرسل إليها شيئًا.
 */
function isBackendListening(): Promise<boolean> {
  return new Promise((resolve) => {
    const probe = net.createServer();
    probe.once('error', (err: NodeJS.ErrnoException) => {
      resolve(err.code === 'EADDRINUSE');
    });
    probe.once('listening', () => probe.close(() => resolve(false)));
    probe.listen(BACKEND_PORT, '127.0.0.1');
  });
}

let baselineHash: string | null = null;
/** هل كان خادم حيّ يعمل عند بدء التشغيل؟ يُحوّل الحكم من «انتهاك» إلى «غير حاسم». */
let backendWasLive = false;

export async function setup(): Promise<void> {
  baselineHash = sha256OfFile(REAL_DEV_DB);
  backendWasLive = await isBackendListening();
  if (backendWasLive) {
    // eslint-disable-next-line no-console
    console.warn(
      '[عزل الاختبارات] ⚠️  رُصد خادم خلفي حيّ على المنفذ ' + BACKEND_PORT + '. ' +
        'العزل نفسه يعمل كالمعتاد (الاختبارات تكتب في الصندوق الرملي وحده)، لكن التحقق ' +
        'النهائي ببصمة قاعدة التطوير سيكون غير حاسم لأن التطبيق قد يكتب فيها أثناء التشغيل. ' +
        'لإثبات قاطع: أغلق نظام المنار ثم أعد تشغيل الاختبارات.',
    );
  }

  // بقايا تشغيل سابق قُتل قبل التنظيف — تُزال حتى يبدأ كل تشغيل من صندوق نظيف.
  try {
    fs.rmSync(SANDBOX_ROOT, { recursive: true, force: true });
  } catch {
    // أفضل جهد — تعذّر الحذف لا يمنع التشغيل، والصناديق معزولة لكل عامل أصلًا.
  }
  fs.mkdirSync(SANDBOX_ROOT, { recursive: true });
}

export async function teardown(): Promise<void> {
  const afterHash = sha256OfFile(REAL_DEV_DB);

  try {
    fs.rmSync(SANDBOX_ROOT, { recursive: true, force: true });
  } catch {
    // أفضل جهد — ملفات مؤقتة يتولّى نظام التشغيل تنظيفها لاحقًا.
  }

  if (baselineHash === null && afterHash === null) return; // لا قاعدة تطوير على هذا الجهاز
  if (baselineHash === afterHash) return;                  // الحالة السليمة: لم يتغيّر شيء

  const details =
    `  الملف      : ${REAL_DEV_DB}\n` +
    `  البصمة قبل : ${baselineHash ?? '(غير موجود)'}\n` +
    `  البصمة بعد : ${afterHash ?? '(غير موجود)'}`;

  // كاتب آخر مشروع كان حيًّا ⇒ النتيجة **غير حاسمة** لا انتهاك. تُبلَّغ بوضوح ولا
  // تُفشل التشغيل: العزل نفسه مضمون من `vitest.setup.ts`، وهذا الحارس إثبات إضافي
  // لا الحماية الأساسية.
  if (backendWasLive || (await isBackendListening())) {
    // eslint-disable-next-line no-console
    console.warn(
      '[عزل الاختبارات] ⚠️  تغيّرت بصمة قاعدة التطوير، لكن خادمًا خلفيًا حيًّا كان يعمل ' +
        'أثناء التشغيل — فالتغيّر يُنسب إليه لا إلى الاختبارات، والنتيجة غير حاسمة.\n' +
        details +
        '\nلإثبات قاطع: أغلق نظام المنار ثم أعد تشغيل الاختبارات.',
    );
    return;
  }

  throw new TestIsolationError(
    '[عزل الاختبارات] ⛔ تغيّرت قاعدة بيانات التطوير أثناء تشغيل الاختبارات، ولا خادم ' +
      'حيّ يُفسّر التغيّر.\n' +
      details +
      '\nهذا انتهاك مباشر لعزل بيئة الاختبارات. ابحث عن اختبار يكتب بمسار مطلق أو ' +
      'يتجاوز DATABASE_URL المضبوط في vitest.setup.ts.',
  );
}
