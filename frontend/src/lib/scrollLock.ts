/**
 * قفل تمرير الصفحة — عدّاد مرجعي مشترك (Reference-Counted Scroll Lock).
 *
 * ── لماذا يلزم عدّاد، ولا يكفي «احفظ القيمة السابقة واستعدها» ──────────────────
 *
 * كان كل سطح حاجب يدير `document.body.style.overflow` بنفسه، بأسلوبين مختلفين:
 *   • `Modal` يكتب `'hidden'` عند الفتح و`''` (قيمة ثابتة) عند الإغلاق.
 *   • `useFocusTrap`/`PrintPreviewDialog` يلتقطان القيمة السابقة ويعيدانها.
 *
 * حين يُكدَّس سطحان (حوار تأكيد فوق نافذة — كما في `CreateInvoice`) ثم يُفرَّغان
 * في **نفس دورة الالتزام** (نجاح الحفظ يستدعي `setConfirming(false)` و`onClose()`
 * معًا فيُفرَّغ الأب كله)، تعمل دوال التنظيف بترتيب المستند لا بترتيب الفتح:
 *
 *     Modal.cleanup   → overflow = ''          ✅
 *     Dialog.cleanup  → overflow = prevOverflow = 'hidden'   ← آخر كاتب يفوز
 *
 * فتبقى الصفحة مقفلة بلا أي نافذة على الشاشة، ولا شيء في النظام يُعيد ضبطها.
 * جذر العلّة أن كل سطح يفترض أنه الوحيد: يستعيد **لقطة** رآها هو، لا الحالة
 * الحقيقية المشتركة.
 *
 * ── العقد هنا ────────────────────────────────────────────────────────────────
 *
 *   • `lockScroll()`   — أول قفل فقط يلتقط القيمة الأصلية ويكتب `'hidden'`.
 *   • `unlockScroll()` — آخر فكّ فقط يعيد القيمة الأصلية.
 *   • ما بينهما لا يلمس الـDOM إطلاقًا.
 *
 * فيصبح **ترتيب التفريغ بلا أهمية**: أي تشابك أو تداخل بين الأسطح ينتهي دائمًا
 * إلى استعادة واحدة صحيحة عند خروج آخر قفل.
 *
 * StrictMode (مفعَّل في `main.tsx`) يُشغّل التأثير مرتين — تشغيل/تنظيف/تشغيل.
 * العدّاد يتعامل مع ذلك طبيعيًا: 1 → 0 (استعادة) → 1 (التقاط جديد لنفس القيمة
 * المستعادة)، فلا تتسرّب حالة ولا تُلتقط `'hidden'` كقيمة «أصلية».
 */

/** عدد الأسطح الحاجبة المفتوحة حاليًا. */
let lockCount = 0;

/** قيمة `body.style.overflow` قبل أول قفل — تُستعاد حرفيًا بعد آخر فكّ. */
let originalOverflow = '';

/**
 * يطلب قفل تمرير الصفحة. آمن للتداخل: النداء الثاني فما فوق يزيد العدّاد فقط.
 * يُقابَل دائمًا بـ `unlockScroll()` واحد (عادةً في تنظيف `useEffect`).
 */
export function lockScroll(): void {
  if (lockCount === 0) {
    originalOverflow = document.body.style.overflow;
    document.body.style.overflow = 'hidden';
  }
  lockCount += 1;
}

/**
 * يُحرّر قفلًا واحدًا. لا يُستعاد التمرير إلا عند خروج آخر قفل.
 *
 * نداء غير متوازن (فكّ بلا قفل) يُتجاهَل بصمت بدل أن يدفع العدّاد إلى السالب —
 * وإلا لاحتاج القفل التالي نداءين ليعمل، وهو عطل أسوأ من الذي نُصلحه.
 */
export function unlockScroll(): void {
  if (lockCount === 0) return;
  lockCount -= 1;
  if (lockCount === 0) {
    document.body.style.overflow = originalOverflow;
    originalOverflow = '';
  }
}

/** عدد الأقفال النشطة — للاختبارات والتشخيص فقط. */
export function activeScrollLocks(): number {
  return lockCount;
}

/**
 * يُعيد الوحدة إلى حالتها الابتدائية. **للاختبارات فقط** — تعزل الحالة على مستوى
 * الوحدة بين الحالات بدل الاعتماد على ترتيب تنفيذها.
 */
export function __resetScrollLockForTests(): void {
  lockCount = 0;
  originalOverflow = '';
}
