/**
 * حالة العرض التي تعود إلى وضعها الافتراضي عند **كل تشغيل جديد للبرنامج**.
 *
 * حالة الصفحة والفرز تُحفَظ في localStorage (usePersistedState) فتنجو من إغلاق
 * البرنامج — وهذا مطلوب داخل الجلسة الواحدة، لكن جدول المعدات يجب أن يبدأ كل
 * تشغيل جديد من الصفحة الأولى ومن الترتيب الافتراضي (الأقرب انتهاءً أولًا).
 *
 * إشارة «تشغيل جديد» هي sessionStorage: يُمسح مع إغلاق نافذة التطبيق ويبقى عبر
 * إعادة تحميل النافذة والتنقّل بين الصفحات — فلا نُبطل اختيار المستخدم أثناء
 * جلسته. حذف المفاتيح (لا كتابة قيم) يجعل usePersistedState يقرأ الافتراضي
 * المعرَّف في مكانه الوحيد: `1` للصفحة، و`ModuleConfig.defaultSort` للفرز.
 */

const RUN_FLAG_KEY = 'manarERP.run.started';

/** مفاتيح `rp:` التي لا تُورَّث بين تشغيلين — الوحدة والغرض بجانب كل مفتاح. */
const RESET_ON_NEW_RUN = [
  'rp:equipment:page', // المعدات: تبدأ دائمًا من الصفحة الأولى
  'rp:equipment:sort', // المعدات: الترتيب الافتراضي = المدة الباقية تصاعديًا
];

/** يُستدعى مرة واحدة عند إقلاع الواجهة، قبل أول رسم. */
export function resetRunStartUIState(): void {
  try {
    if (sessionStorage.getItem(RUN_FLAG_KEY)) return; // نفس التشغيل (إعادة تحميل)
    sessionStorage.setItem(RUN_FLAG_KEY, '1');
    RESET_ON_NEW_RUN.forEach((key) => localStorage.removeItem(key));
  } catch {
    /* التخزين غير متاح — القيم الافتراضية تُستخدم أصلًا في هذه الحالة */
  }
}
