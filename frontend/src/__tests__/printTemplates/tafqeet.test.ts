import { describe, it, expect } from 'vitest';
import { tafqeet } from '../../lib/tafqeet';

describe('tafqeet — KWD number-to-words', () => {
  // ── Zero ──────────────────────────────────────────────────────────────────

  it('0 → صفر دينار كويتي', () => {
    expect(tafqeet(0)).toBe('صفر دينار كويتي فقط لا غير');
  });

  // ── Single dinar ──────────────────────────────────────────────────────────

  it('1 → دينار كويتي واحد', () => {
    expect(tafqeet(1)).toBe('واحد دينار كويتي فقط لا غير');
  });

  // ── Dual ──────────────────────────────────────────────────────────────────

  it('2 → اثنان ديناران كويتيان', () => {
    expect(tafqeet(2)).toBe('اثنان ديناران كويتيان فقط لا غير');
  });

  // ── 11–12 (special teens) ─────────────────────────────────────────────────

  it('11 → أحد عشر ديناراً كويتياً', () => {
    expect(tafqeet(11)).toBe('أحد عشر ديناراً كويتياً فقط لا غير');
  });

  it('12 → اثنا عشر ديناراً كويتياً', () => {
    expect(tafqeet(12)).toBe('اثنا عشر ديناراً كويتياً فقط لا غير');
  });

  // ── Compound (21–99) ──────────────────────────────────────────────────────

  it('21 → واحد وعشرون ديناراً كويتياً', () => {
    expect(tafqeet(21)).toBe('واحد وعشرون ديناراً كويتياً فقط لا غير');
  });

  // ── Hundreds ──────────────────────────────────────────────────────────────

  it('100 → مائة ديناراً كويتياً', () => {
    expect(tafqeet(100)).toBe('مائة ديناراً كويتياً فقط لا غير');
  });

  it('200 → مائتان ديناراً كويتياً', () => {
    expect(tafqeet(200)).toBe('مائتان ديناراً كويتياً فقط لا غير');
  });

  // ── Thousands ─────────────────────────────────────────────────────────────

  it('1000 → ألف ديناراً كويتياً', () => {
    expect(tafqeet(1000)).toBe('ألف ديناراً كويتياً فقط لا غير');
  });

  it('1001 → ألف وواحد ديناراً كويتياً', () => {
    expect(tafqeet(1001)).toBe('ألف وواحد ديناراً كويتياً فقط لا غير');
  });

  it('1002 → ألف واثنان ديناراً كويتياً', () => {
    expect(tafqeet(1002)).toBe('ألف واثنان ديناراً كويتياً فقط لا غير');
  });

  it('11000 → أحد عشر ألفاً ديناراً كويتياً', () => {
    expect(tafqeet(11000)).toBe('أحد عشر ألفاً ديناراً كويتياً فقط لا غير');
  });

  // ── Millions ──────────────────────────────────────────────────────────────

  it('1000000 → مليون ديناراً كويتياً', () => {
    expect(tafqeet(1000000)).toBe('مليون ديناراً كويتياً فقط لا غير');
  });

  it('1000500 → مليون وخمسمائة ديناراً كويتياً', () => {
    expect(tafqeet(1000500)).toBe('مليون وخمسمائة ديناراً كويتياً فقط لا غير');
  });

  // ── With fils ─────────────────────────────────────────────────────────────

  it('0.500 → صفر dinars + خمسمائة فلساً', () => {
    const result = tafqeet(0.5);
    expect(result).toContain('خمسمائة');
    expect(result).toContain('فلس');
    expect(result).toContain('فقط لا غير');
  });

  it('732.500 → contains سبعمائة', () => {
    const result = tafqeet(732.5);
    expect(result).toContain('سبعمائة');
    expect(result).toContain('فقط لا غير');
  });

  // ── Suffix always present ─────────────────────────────────────────────────

  it('always ends with فقط لا غير', () => {
    [0, 1, 2, 5, 11, 100, 1000, 5000].forEach((n) => {
      expect(tafqeet(n)).toMatch(/فقط لا غير$/);
    });
  });

  // ── Non-finite / negative guard ───────────────────────────────────────────

  it('returns empty string for Infinity', () => {
    expect(tafqeet(Infinity)).toBe('');
  });

  it('returns empty string for NaN', () => {
    expect(tafqeet(NaN)).toBe('');
  });
});
