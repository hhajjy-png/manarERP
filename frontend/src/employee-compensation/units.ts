/**
 * وحدات العرض داخل وحدة مستحقات الموظف الشهرية — **هذه الوحدة وحدها**.
 *
 * ═══ لماذا ملف محلّي لا تعديل في المُنسّق المشترك ═══
 * `formatCurrency` في `lib/format` و`money` في `config/modules` و`money` في
 * `forms/shared/formStyles` تخدم النظام كلّه: الفواتير، الشيكات، المحاسبة، الرواتب،
 * النماذج الإدارية الأربعة عشر. تغيير الرمز فيها كان سيغيّر كل مستند في المشروع من
 * أجل طلبٍ نطاقُه كشوف هذه الوحدة. فيُلفّ المُنسّق المشترك هنا ويُستبدل **اللاحقة
 * وحدها**، ويستورد هذا الملفَّ من يخصّه.
 *
 * ═══ عرضٌ لا عملة ═══
 * عملة المشروع تبقى `KWD` حرفيًا: التخزين، الحسابات، الدقّة الثلاثية، حمولات الـAPI،
 * التصدير البنكي، القيود المحاسبية — لا يمسّها هذا الملف بحرف. ما يتغيّر هو النصّ
 * المطبوع بجانب الرقم في كشوف هذه الوحدة.
 */
import { formatNumber } from '../lib/format';

/** رمز العملة **المعروض** في كشوف هذه الوحدة. لا علاقة له بـ`currencyConfig.code`. */
export const KD = 'KD';

/** وحدة الزمن **المعروضة** في تفاصيل الحسبة — مفردة موحّدة لا تُصرَّف. */
export const HOUR_UNIT = 'hour';

/**
 * مبلغ داخل نصّ عربي — معزول اتجاهيًا كي لا يقلب محرّك bidi ترتيب «28.000 KD».
 * نفس تنسيق الرقم المشترك (ثلاث خانات، أرقام غربية)؛ اللاحقة وحدها هي المختلفة.
 */
export function kd(value: unknown): string {
  return `⁦${formatNumber(value)} ${KD}⁩`;
}

/** المبلغ بلا معزولات — لخلايا الجداول التي تفرض اتجاهها بالتنسيق أصلًا. */
export function kdPlain(value: unknown): string {
  return `${formatNumber(value)} ${KD}`;
}

/** عدد ساعات معروض: «7 hour» — الوحدة مفردة دائمًا مهما بلغ العدد. */
export function hours(value: number): string {
  return `⁦${value} ${HOUR_UNIT}⁩`;
}
