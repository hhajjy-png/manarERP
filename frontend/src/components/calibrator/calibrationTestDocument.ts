/**
 * ورقة اختبار المعايرة — تركيب مستند المعاينة من **العقدة المطبوعة نفسها**.
 *
 * ليست مولّدًا ثانيًا للورقة. الورقة يرسمها `CalibrationTestSheet` مرة واحدة داخل
 * `.chq-calib-testprint` المخفيّة، ومسار الطباعة القديم يطبع **تلك العقدة بعينها**
 * (`printCurrentView` → `webContents.print` على مستند التطبيق). هذه الدالة تُسلسل نفس
 * العقدة إلى مستند مكتفٍ بذاته لعرضه في `<iframe srcdoc>` — لا أكثر.
 *
 * لماذا لا نحتاج التقاط أنماط (`composeStyledFromNode`)؟
 * ────────────────────────────────────────────────────────
 * لأن الورقة **بلا أنماط CSS أصلًا**: كل حدّ ولون وخط وإحداثية فيها خاصية عرض على عنصر
 * SVG (`stroke` · `fill` · `font-size`) داخل `viewBox` بالمليمتر. أصنافها
 * (`chq-test-sheet` · `chq-ruler*` · `chq-test-*`) لا تطابق أي قاعدة CSS في المشروع.
 * فالعقدة المُسلسَلة **هي** المستند كاملًا. حقن أنماط التطبيق هنا كان سيُدخل متغيّرات
 * الوضع الداكن وقواعد `svg` العامة إلى ورقة قياس فيزيائي — خطرٌ بلا مقابل.
 *
 * ولماذا لا نبني الورقة من الهندسة مباشرة؟ لأن ذلك يخلق مصدرَي حقيقة: نسخة تُعرض وأخرى
 * تُطبع، تفترقان عند أول تعديل. المعروض هو المطبوع — حرفيًا نفس العقدة.
 *
 * المستند الناتج **للشاشة فقط**: لا `@page` فيه ولا قواعد طباعة. الطباعة الفعلية لا تمرّ
 * من هنا إطلاقًا — تبقى على مستند التطبيق الحيّ بقواعده الأصلية.
 */

/** العقدة الجذر لورقة الاختبار داخل الطبقة المخفيّة — نفس ما يُصيّره `CalibrationTestSheet`. */
export const TEST_SHEET_ROOT_SELECTOR = '.chq-calib-testprint .chq-test-sheet';

/** رسالة عربية واحدة لكل إخفاق تجهيز — تُعرض للمستخدم في نافذة المعاينة. */
const COMPOSE_FAILED = 'تعذّر تجهيز ورقة اختبار المعايرة للمعاينة. أغلق النافذة وأعد المحاولة.';

/**
 * يُسلسل ورقة الاختبار المُصيَّرة إلى مستند HTML مكتفٍ بذاته.
 *
 * يرمي خطأً عربيًا واضحًا — ولا يُرجع مستندًا ناقصًا — إذا لم تكن الورقة موجودة أو خلت من
 * الـ SVG. المعاينة تعرض الخطأ ولا تطبع، وهو المطلوب: ورقة قياس خاطئة أسوأ من لا ورقة.
 */
export function composeCalibrationTestDocument(node: HTMLElement | null): string {
  if (!node) throw new Error(COMPOSE_FAILED);

  // الورقة كلها SVG. غيابه يعني عقدة غير مكتملة — لا نعاين شيئًا لا نعرف ما هو.
  if (!node.querySelector('svg')) throw new Error(COMPOSE_FAILED);

  // نسخة — الـ DOM الحيّ (وهو المطبوع) لا يُمسّ أبدًا.
  const clone = node.cloneNode(true) as HTMLElement;

  // الطبقة الحاوية `display:none`؛ العقدة نفسها ليست كذلك، لكن نُحيّد أي إخفاء موروث
  // نُسخ مع الخصائص السطرية، وإلا خرجت المعاينة بيضاء فارغة.
  clone.style.removeProperty('display');
  clone.style.removeProperty('visibility');

  // علامة القياس التي تقرأها `PrintPreviewDialog` لتقدير عدد الصفحات. بدونها يقيس
  // `document.body` — و`scrollHeight` للـ body **لا يقلّ أبدًا عن ارتفاع الـ viewport**،
  // وهو هنا ارتفاع الـ iframe نفسه؛ فتجاوزٌ كسريّ من بكسل واحد كان يكفي لإعلان «صفحتين»
  // وإلحاق امتداد أبيض طويل بورقة من صفحة واحدة (نفس نكسة الصفحة الوهمية المعروفة).
  // القياس على العنصر ارتفاعٌ عنصريّ خالص: ورقة A4 أفقية واحدة ⇒ صفحة واحدة، دائمًا.
  clone.setAttribute('data-print-root', '');

  const html = clone.outerHTML;
  if (!html.trim()) throw new Error(COMPOSE_FAILED);

  // `dir="rtl"` يطابق مستند التطبيق الذي تُطبع منه الورقة فعلًا (‎<html dir="rtl">‎)، فتُشكَّل
  // النصوص العربية في المعاينة كما تُشكَّل على الورق تمامًا.
  return `<!DOCTYPE html>
<html dir="rtl" lang="ar">
<head>
<meta charset="UTF-8">
<meta name="color-scheme" content="light">
<title>معاينة اختبار المعايرة</title>
<style>
  /* ورقة قياس: خلفية بيضاء صريحة وهوامش صفرية. لا إطار، ولا ظل، ولا حدّ — أي زينة هنا
     كانت ستُظهر إطارًا حول الورقة يوحي بأنه جزء منها (وهي بعينها نكسة الإطار الأسود
     التي عولجت سابقًا). تنسيق المعاينة — الظل والحدّ والتوسيط — يملكه .pc-sheet في
     الحاوية، خارج هذا المستند تمامًا. */
  :root { color-scheme: light; }
  html, body {
    margin: 0;
    padding: 0;
    background: #fff;
    border: 0;
  }
  /* الورقة مقاسة بالمليمتر في خصائصها السطرية (‎297mm × 210mm‎ افتراضيًا) — لا نلمس
     مقاسها هنا بأي حال: هو المقاس الفيزيائي نفسه الذي تُطبع به. */
</style>
</head>
<body>${html}</body>
</html>`;
}
