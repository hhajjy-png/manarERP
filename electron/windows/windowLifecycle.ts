import type { BrowserWindow } from 'electron';

/**
 * سجلّ دورة حياة النوافذ — يفصل بين "نوافذ مساعدة" مؤقتة (حوار تقدّم المزامنة،
 * أي شاشة بدء تشغيل مستقبلية مثل شاشة تحميل أو تحقّق من التحديثات) و"النافذة
 * الرئيسية" الفعلية للتطبيق. الهدف الوحيد لهذا الملف: منع إغلاق آخر نافذة
 * مساعدة — قبل إنشاء النافذة الرئيسية، أو بعد إغلاقها لاحقًا — من أن يُفسَّر
 * خطأً كطلب من المستخدم لإنهاء التطبيق (حدث `window-all-closed` في Electron
 * لا يميّز بين نوع النوافذ، فقط يحتسب العدد).
 *
 * عام تمامًا: لا يعرف شيئًا عن المزامنة أو أي نافذة محدّدة بالاسم. أي نافذة
 * مساعدة مستقبلية تُسجّل نفسها هنا بنفس الاستدعاء وتحصل على نفس الحماية
 * تلقائيًا — لا حاجة لتعديل هذا الملف أو منطق دورة الحياة في main.ts لإضافة
 * نافذة مساعدة جديدة.
 */

const utilityWindows = new Set<BrowserWindow>();
let mainWindowEverRegistered = false;

/** يُسجَّل عند إنشاء أي نافذة مساعدة مؤقتة — تُزال تلقائيًا من السجلّ عند إغلاقها. */
export function registerUtilityWindow(win: BrowserWindow): void {
  utilityWindows.add(win);
  win.once('closed', () => {
    utilityWindows.delete(win);
  });
}

/**
 * يُسجَّل عند إنشاء النافذة الرئيسية الفعلية للتطبيق. استدعاء واحد يكفي —
 * بعده يُعتبر التطبيق قد "بدأ فعليًا"، بغضّ النظر عمّا إذا أُغلقت هذه النافذة
 * لاحقًا (لا يُعاد ضبطه إلى false أبدًا).
 */
export function registerMainWindow(_win: BrowserWindow): void {
  mainWindowEverRegistered = true;
}

/** هل هذه نافذة مساعدة مُسجَّلة (وليست النافذة الرئيسية)؟ */
export function isUtilityWindow(win: BrowserWindow): boolean {
  return utilityWindows.has(win);
}

/**
 * هل يجب أن يعني وصول عدد النوافذ المفتوحة إلى صفر إنهاء التطبيق؟
 *
 * لا — إن لم تُنشأ النافذة الرئيسية بعد. في تلك الحالة، إغلاق آخر نافذة مساعدة
 * (كحوار تقدّم مزامنة بدء التشغيل) هو مجرّد انتهاء عرضها المؤقت، وليس إشارة
 * إلى رغبة المستخدم بإغلاق تطبيق لم تظهر نافذته الرئيسية له أصلًا بعد.
 *
 * نعم — بمجرّد أن تُنشأ النافذة الرئيسية مرّة واحدة، يعود السلوك المعتاد:
 * وصول عدد النوافذ إلى صفر يعني إغلاق التطبيق (تحت ويندوز/لينكس).
 */
export function shouldQuitOnAllWindowsClosed(): boolean {
  return mainWindowEverRegistered;
}
